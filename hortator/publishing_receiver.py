"""Standalone, standard-library-only receiver for immutable static publications.

Install this file on the publishing host; it deliberately imports no Hortator
modules and has no credentials. SSH authenticates the trusted local worker.
Model tools never invoke this receiver or choose its bot_id themselves.

Usage: python3 publishing_receiver.py --web-root /srv/www/council \
    --state-root /srv/council-publishing deploy|status|audit
Deploy/status read one bounded JSON object from stdin. Audit needs no stdin.
"""

